'use strict';
const assert = require('node:assert/strict');
require('./dist/cardio.js');
const clock = globalThis.CardioClock;
const now = Date.parse('2026-10-29T10:00:00Z');
let draft = clock.makeDraft({ date: '2026-10-29', plannedType: 'run', targetMinutes: 20 }, now);
assert.equal(draft.type, 'running');
assert.equal(clock.elapsed(draft, now + 100000), 0);
draft = clock.start(draft, now);
assert.equal(clock.elapsed(draft, now + 65000), 65000);
draft = clock.pause(draft, now + 65000);
assert.equal(clock.elapsed(draft, now + 500000), 65000);
draft = clock.start(draft, now + 500000);
assert.equal(clock.elapsed(draft, now + 530000), 95000);
const restored = clock.normalizeDraft(JSON.parse(JSON.stringify(draft)));
assert.equal(clock.elapsed(restored, now + 630000), 195000);
draft = clock.stop(restored, now + 630001);
assert.equal(draft.editedSeconds, 196);
draft.distance = '2.5';
const saved = clock.record(draft, now + 630001);
assert.equal(saved.seconds, 196);
assert.equal(saved.distanceKm, 2.5);
assert.equal(saved.date, '2026-10-29');
assert.equal(saved.source, 'timer');
assert.equal(clock.duration(3661000), '01:01:01');
assert.equal(clock.elapsed(clock.start(clock.makeDraft({}, now), now), now - 1000), 0);
assert.equal(clock.normalizeDraft({ ...draft, date: '2026-02-30' }), null);
assert.equal(clock.normalizeDraft({ ...draft, status: 'running', startedAt: null }), null);
const empty = clock.makeDraft({}, now);
assert.throws(() => clock.record(empty, now), /计时不足/);
const short = clock.stop(clock.start(empty, now), now + 40);
assert.equal(clock.record(short, now + 40).seconds, 1);
let manual = { ...clock.makeDraft({ date: '2026-10-29', plannedType: 'swimming' }, now), mode: 'manual', distance: '500' };
assert.equal(clock.record(manual, now).distanceKm, .5);
assert.equal(clock.record(manual, now).seconds, null);
assert.equal(clock.record(manual, now).durationUnknown, true);
manual.manualMinutes = '12'; manual.manualSeconds = '30';
assert.equal(clock.record(manual, now).seconds, 750);
manual.distance = '-1'; assert.throws(() => clock.record(manual, now), /检查游泳距离/);
manual.distance = '500'; manual.manualSeconds = '60'; assert.throws(() => clock.record(manual, now), /检查秒/);
manual.manualSeconds = '.5'; assert.throws(() => clock.record(manual, now), /整数/);
const stairs = { ...clock.makeDraft({ plannedType: 'stairs' }, now), mode: 'manual', floors: '20' };
assert.equal(clock.record(stairs, now).floors, 20);
stairs.floors = '1.5'; assert.throws(() => clock.record(stairs, now), /整数/);
assert.throws(() => clock.record({ ...empty, mode: 'manual' }, now), /填写运动/);
assert.throws(() => clock.record({ ...short, editedSeconds: 86401 }, now), /24 小时/);
console.log('CardioClock: pause/resume, refresh recovery, distance-only, validation and sub-second records passed.');
