const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const read = name => fs.readFileSync(path.join(__dirname, name), 'utf8');
const manifest = read('android/app/src/main/AndroidManifest.xml');
const activity = read('android/app/src/main/java/com/swaggyer/baojiboji/MainActivity.java');
const gradle = read('android/app/build.gradle');
const photos = read('dist/photo-meal.js');
assert.match(gradle, /from\(rootProject\.file\('\.\.\/dist'\)\)/);
assert.match(gradle, /dependsOn 'syncWebAssets'/);
assert.match(activity, /WebViewAssetLoader\.AssetsPathHandler/);
assert.match(activity, /appassets\.androidplatform\.net/);
assert.match(activity, /\/assets\/web\/index\.html/);
assert.match(activity, /setJavaScriptEnabled\(true\)/);
assert.match(activity, /setDomStorageEnabled\(true\)/);
assert.match(activity, /setAllowFileAccess\(false\)/);
assert.match(activity, /MIXED_CONTENT_NEVER_ALLOW/);
assert.match(manifest, /usesCleartextTraffic="false"/);
const permissions = Array.from(manifest.matchAll(/<uses-permission[^>]+android:name="([^"]+)"/g), match => match[1]);
assert.deepEqual(permissions, ['android.permission.INTERNET','android.permission.REQUEST_INSTALL_PACKAGES']);
assert.ok(!activity.includes('addJavascriptInterface'));
assert.match(activity, /MediaStore\.ACTION_IMAGE_CAPTURE/);
assert.match(activity, /FileProvider\.getUriForFile/);
assert.match(activity, /MediaStore\.EXTRA_OUTPUT/);
assert.match(activity, /FLAG_GRANT_WRITE_URI_PERMISSION/);
assert.match(activity, /Intent\.ACTION_OPEN_DOCUMENT/);
assert.match(activity, /setType\("image\/\*"\)/);
assert.match(activity, /FileChooserParams\.MODE_OPEN_MULTIPLE/);
assert.match(activity, /callback\.onReceiveValue\(images\)/);
assert.match(activity, /dialog\[open\]/);
assert.match(activity, /webView\.goBack\(\)/);
assert.match(activity, /Intent\.ACTION_VIEW/);
assert.match(photos, /capture="environment"/);
assert.match(read('android/app/src/main/res/xml/file_paths.xml'), /path="meal-photos\/"/);
assert.match(read('android/ci/android-build.yml'), /:app:assembleDebug :app:lintDebug/);
assert.ok(fs.existsSync(path.join(__dirname, 'dist/index.html')));
assert.ok(fs.existsSync(path.join(__dirname, 'dist/assets/brand-abs-bolt.svg')));
console.log('Android source contract passed: bundled web assets, local storage, image capture/picker, restricted navigation, back handling, minimal permissions and CI build configuration. Compilation and device testing remain separate checks.');
